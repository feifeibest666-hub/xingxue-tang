const A20 = `**1. 占星是科学吗？**
星盘上的天体位置能复算，这一层是天文学。象征是文化传统。预测主张没有被严格检验支持，不能把整门占星叫做科学。

**2. 既然没有证据，为什么还要学？**
学到的是天文、几何、历史、语言，以及怎样检验一个说法。占星作为文化值得懂。懂了才能既不盲从，也不空骂。

**3. 有没有研究支持占星？**
戈奎林从 1955 年起报告火星关键区约 22% 对预期约 17%。Comité Para（1976）看到类似现象但怀疑人口假象；美国 CSICOP（1970 年代末）没有看到效应且争议很大；法国 CFEPP 约 1000 名冠军（1996）没有看到效应。他自己也不支持星座和相位。卡尔森 1985：40/116 约 34%，随机约 33%，预期至少 50%。Dean 与 Kelly（2003）的时间双胞胎没有超出随机的相似。

**4. 我自己觉得很准，为什么不算证据？**
觉得准会被确认偏差、冷读和巴纳姆式的句子放大。检验要事先写定对错，并和基线比。个人印象没有这些步骤。

**5. 双盲实验是不是对占星不公平？**
卡尔森实验的设计事先与占星师同意，他们预期至少 50%。双盲挡的是提示，不是挡技术。结果约 34%，接近 33%。

**6. 116 张盘是不是太少？**
若真有他们预期的至少 50%，116 张里至少是 58 张，实际是 40 张。这不是"差一点点没测出来"。样本大小不能把 34% 说成 50%。

**7. 火星效应不是已经被证实了吗？**
它是一个很窄的报告：约 22% 对约 17%，而且后来没有被稳住。法国约 1000 人的检验没有看到效应。它也不支持星座和相位。

**8. 时间双胞胎说明了什么？**
1958 年 3 月初在伦敦出生的 2101 人，约 110 项指标，平均相隔约 4.8 分钟，没有超出随机的相似。星盘几乎一样，人并不因此更像。

**9. 为什么星座描述人人都觉得像自己？**
福勒 1949：39 名学生给同一段通用描述打分，平均 4.26（满分 5）。米尔 1956 年称之为巴纳姆效应。觉得像，不等于把人区分开了。

**10. 占星是象征语言，本来就不该用统计检验？**
若它只作为象征和反思、不再声称测得准，它可以不接受预测检验。一旦句子承诺了可核对的事，就可以检验。

**11. 占星是占卜不是因果，所以实验无效？**
科尼利厄斯把占星看成占卜，不是天体造成事件。占卜若仍说出可核对的结果，核对并不需要因果这个前提。若它拒绝任何核对，就不能被证伪，也不能被证实。

**12. 古代天文学家都做占星，所以占星有道理？**
托勒密、开普勒、伽利略确实也做占星。这说明在他们的时代两者没有分开。17 世纪以后，大学和科学学会不再把占星当作学问的一部分。一个人两件事都做，不使预测自动成立。

**13. 中国古代也有星占，是不是说明它普遍为真？**
中国星占长期以国家、灾异、分野为中心，《史记·天官书》是早期总述。个人推命如七政四余是后来的，受到印度、波斯占星的影响。古老说明它是文化，不是证明预测。

**14. 别的领域也有不准的测试，为什么要单批占星？**
不准的测试在别的领域里同样要交出证据：事先说清测什么，再看是否优于基线。不能因为别处也有问题，这里就可以不算。

**15. 你自己没做实验，凭什么下结论？**
可以自己做预测日记，和第 640 天一样与基线比。公开实验的意义是规则事先定好、做过盲法、样本比个人印象大。个人再验一次是好事，不能把已经做过的计数当成没发生。

**16. 占星对自我反思有用，这算不算准？**
有用可以是真的：一段话让你想清楚一件事，这是心理和文化上的价值。这不等于出生时刻预示了这件事。两种价值要分开。

**17. 如果没有预测力，为什么还有人靠它做决定？**
巴纳姆式的吻合、确认偏差、冷读、自我实现，都会让人觉得可靠。觉得可靠是第 631 天的题目，不是预测力的证据。

**18. 太阳星座和上升星座，哪个更科学？**
两者的天文位置都同样可以算准。没有证据显示其中一个的性格预测更成立。时间双胞胎里上升只差大约 1° 的人，也没有更相似。更细，不等于更科学。

**19. 能不能用占星看健康或寿命？**
不能。不做健康诊断，不预言死亡。既是因为没有那种证据，也是因为伤害很大。身体的事去看医生。

**20. 规则学了这么多，是不是白学了？**
不白学。规则让你看懂传统在说什么，也看懂证据停在哪里。白学的是把规则当成已经证实的自然定律。`

